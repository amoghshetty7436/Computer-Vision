"""Aggregate all result CSVs into summary tables (results/summary.md) and figures (results/figures).

  python scripts/analyze.py --raw results/raw --out results
Works on partial results (whatever CSVs exist). Error bars = 95% bootstrap CI over
seeds x scenes (controlled) or anchors x sequences x seeds (Boreas).
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

# reference categorical palette (fixed order) + text/grid tokens
PAL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"
plt.rcParams.update({
    "font.size": 10, "axes.edgecolor": INK2, "axes.labelcolor": INK, "xtick.color": INK2,
    "ytick.color": INK2, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    "axes.spines.top": False, "axes.spines.right": False, "lines.linewidth": 2,
    "legend.frameon": False, "figure.dpi": 150, "savefig.bbox": "tight",
})

METRIC = "auc@10"


def ci(x, n=2000, seed=0):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) == 0:
        return np.nan, np.nan, np.nan
    if len(x) == 1:
        return x[0], x[0], x[0]
    rng = np.random.default_rng(seed)
    bs = rng.choice(x, (n, len(x))).mean(1)
    return x.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def load(raw: Path, pattern: str) -> pd.DataFrame:
    fs = sorted(raw.glob(pattern))
    if not fs:
        return pd.DataFrame()
    df = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    # a run can be logged twice if two resumable queues overlapped: keep the first
    key = [k for k in ("exp", "scene", "cond", "seq", "query_seq", "anchor", "perturb", "severity", "seed") if k in df.columns]
    return df.drop_duplicates(subset=key, keep="first").reset_index(drop=True)


def agg(df, keys, metrics=(METRIC, "reg_frac")):
    rows = []
    for k, g in df.groupby(keys, dropna=False):
        r = dict(zip(keys, k if isinstance(k, tuple) else (k,)))
        r["n"] = len(g)
        for m in metrics:
            mu, lo, hi = ci(g[m])
            r[m], r[m + "_lo"], r[m + "_hi"] = mu, lo, hi
        rows.append(r)
    cols = list(keys) + ["n"] + [m + sfx for m in metrics for sfx in ("", "_lo", "_hi")]
    return pd.DataFrame(rows, columns=cols)


def severity_curves(df, perturbs, title, path, clean_val=None):
    fig, ax = plt.subplots(figsize=(6.4, 4))
    for i, p in enumerate(perturbs):
        g = agg(df[df.perturb == p], ["severity"]).sort_values("severity")
        if g.empty:
            continue
        xs = [0] + g.severity.tolist() if clean_val is not None else g.severity.tolist()
        ys = [clean_val] + g[METRIC].tolist() if clean_val is not None else g[METRIC].tolist()
        c = PAL[i % len(PAL)] if i < len(PAL) else INK2
        ls = "-" if i < len(PAL) else "--"
        ax.plot(xs, ys, ls, color=c, marker="o", ms=4, label=p.replace("_", " "))
        ax.fill_between(g.severity, g[METRIC + "_lo"], g[METRIC + "_hi"], color=c, alpha=0.12, lw=0)
    ax.set_xlabel("severity (0 = clean)")
    ax.set_ylabel("pose AUC@10° (higher is better)")
    ax.set_ylim(-0.02, 1.02)
    ax.set_title(title, loc="left", color=INK)
    ax.legend(fontsize=8, ncol=2, loc="lower left")
    fig.savefig(path)
    plt.close(fig)


def table_md(g, cols):
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in g.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                lo, hi = r.get(c + "_lo"), r.get(c + "_hi")
                cells.append(f"{v:.3f}" + (f" [{lo:.2f}, {hi:.2f}]" if lo is not None and not pd.isna(lo) and r["n"] > 1 else ""))
            else:
                cells.append(str(v))
        out += "| " + " | ".join(cells) + " |\n"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="results/raw")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    raw, out = Path(a.raw), Path(a.out)
    figs = out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    md = ["# Results summary (auto-generated by scripts/analyze.py)\n",
          f"Metric: pose AUC@10° over all input image pairs (unregistered = failure) and registration rate. "
          f"Brackets: 95% bootstrap CI.\n"]

    ctrl = load(raw, "e*__*.csv")
    clean_auc = None
    if not ctrl.empty:
        clean = ctrl[(ctrl.perturb == "clean") & (ctrl.features == "sift") & (ctrl.mapper == "incremental")]
        if len(clean):
            clean_auc = clean[METRIC].mean()
            md.append(f"\n## Clean baseline (SIFT + incremental)\n\n{len(clean)} runs, AUC@10 = {clean_auc:.3f} (std {clean[METRIC].std():.3f}), "
                      f"registration {clean.reg_frac.mean():.3f}.\n")
            for sc, g in clean.groupby("scene"):
                md.append(f"* {sc}: {len(g)} runs, AUC@10 {g[METRIC].mean():.3f} (min {g[METRIC].min():.3f})\n")
        for exp, title in [("e2_analytic", "E2a  Analytic corruptions"),
                           ("e2_generative", "E2b  Generative corruptions"),
                           ("e1_synth_weather", "E1s  Synthetic weather incl. desert")]:
            d = ctrl[(ctrl.exp == exp) & (ctrl.perturb != "clean")]
            if d.empty:
                continue
            ps = list(dict.fromkeys(d.perturb))
            severity_curves(d, ps, title, figs / f"{exp}.png", clean_auc)
            g = agg(d, ["perturb", "severity"]).sort_values(["perturb", "severity"])
            md.append(f"\n## {title}\n\n![]({'figures/' + exp + '.png'})\n\n" + table_md(g, ["perturb", "severity", "n", METRIC, "reg_frac"]))

        d = ctrl[ctrl.exp == "e3_superres"]
        if not d.empty:
            d = d.assign(method=d.perturb.str.replace("sr_", "", regex=False))
            g = agg(d[d.perturb != "clean"], ["severity", "method"])
            fig, ax = plt.subplots(figsize=(6.4, 4))
            methods = ["lowres", "bicubic", "unsharp_bicubic", "realesrgan", "sd_x4"]
            facs = sorted(g.severity.unique())
            w = 0.8 / len(methods)
            for i, m in enumerate(methods):
                gm = g[g.method == m].set_index("severity").reindex(facs)
                if gm[METRIC].isna().all():
                    continue
                x = np.arange(len(facs)) + (i - len(methods) / 2 + 0.5) * w
                ax.bar(x, gm[METRIC], w * 0.9, color=PAL[i], label=m)
            if clean_auc is not None:
                ax.axhline(clean_auc, color=INK2, ls="--", lw=1)
                ax.text(len(facs) - 0.5, clean_auc + 0.01, "native resolution", ha="right", color=INK2, fontsize=8)
            ax.set_xticks(range(len(facs)), [f"×{int(f)} down" for f in facs])
            ax.set_ylabel("pose AUC@10°"); ax.set_ylim(0, 1.05)
            ax.set_title("E3  Super-resolution before SfM", loc="left")
            ax.legend(fontsize=8)
            fig.savefig(figs / "e3_superres.png"); plt.close(fig)
            md.append("\n## E3  Super-resolution\n\n![](figures/e3_superres.png)\n\n" + table_md(g.sort_values(["severity", "method"]), ["severity", "method", "n", METRIC, "reg_frac"]))

        d = ctrl[ctrl.exp == "e4_crowds"]
        if not d.empty:
            fig, ax = plt.subplots(figsize=(6.4, 4))
            from sfmrob.perturb.crowds import CROWD_LEVELS
            for i, mit in enumerate(["none", "mask", "lama_remove"]):
                g = agg(d[(d.mitigation == mit) & (d.perturb == "crowd")], ["severity"]).sort_values("severity")
                if g.empty:
                    continue
                xs = [0] + [CROWD_LEVELS[int(s)] for s in g.severity]
                ys = [clean_auc] + g[METRIC].tolist()
                ax.plot(xs, ys, color=PAL[i], marker="o", ms=4, label={"none": "no mitigation", "mask": "mask people (COLMAP masks)", "lama_remove": "remove people (LaMa inpaint)"}[mit])
            ax.set_xlabel("tourists per image"); ax.set_ylabel("pose AUC@10°"); ax.set_ylim(-0.02, 1.02)
            ax.set_title("E4  Tourist crowds and mitigations", loc="left"); ax.legend(fontsize=8)
            fig.savefig(figs / "e4_crowds.png"); plt.close(fig)
            g = agg(d[d.perturb == "crowd"], ["mitigation", "severity"]).sort_values(["mitigation", "severity"])
            md.append("\n## E4  Crowds\n\n![](figures/e4_crowds.png)\n\n" + table_md(g, ["mitigation", "severity", "n", METRIC, "reg_frac"]))

        d = ctrl[ctrl.exp == "e5_contamination"]
        if not d.empty:
            fig, ax = plt.subplots(figsize=(6.4, 4))
            for i, (p, gp) in enumerate(d[d.perturb != "clean"].groupby("perturb")):
                g = agg(gp, ["frac"]).sort_values("frac")
                ax.plot([0] + g.frac.tolist(), [clean_auc] + g[METRIC].tolist(), color=PAL[i], marker="o", ms=4, label=p)
            ax.set_xlabel("fraction of images corrupted"); ax.set_ylabel("pose AUC@10°"); ax.set_ylim(-0.02, 1.02)
            ax.set_title("E5  How many bad photos break SfM?", loc="left"); ax.legend(fontsize=8)
            fig.savefig(figs / "e5_contamination.png"); plt.close(fig)
            g = agg(d, ["perturb", "severity", "frac"]).sort_values(["perturb", "frac"])
            md.append("\n## E5  Contamination\n\n![](figures/e5_contamination.png)\n\n" + table_md(g, ["perturb", "frac", "n", METRIC, "reg_frac"]))

        d = ctrl[ctrl.exp == "e6_methods"]
        if not d.empty:
            d = d.assign(method=d.features + "+" + d.mapper, condition=d.perturb + "_s" + d.severity.astype(str))
            piv = d.pivot_table(index="condition", columns="method", values=METRIC, aggfunc="mean")
            fig, ax = plt.subplots(figsize=(6.4, 0.4 * len(piv) + 1.2))
            im = ax.imshow(piv.values, cmap="Blues", vmin=0, vmax=1, aspect="auto")
            ax.set_xticks(range(piv.shape[1]), piv.columns, rotation=20); ax.set_yticks(range(len(piv)), piv.index)
            ax.grid(False)
            for (r, c), v in np.ndenumerate(piv.values):
                if not np.isnan(v):
                    ax.text(c, r, f"{v:.2f}", ha="center", va="center", color="white" if v > 0.6 else INK, fontsize=8)
            ax.set_title("E6  Features x mapper (AUC@10°)", loc="left")
            fig.savefig(figs / "e6_methods.png"); plt.close(fig)
            md.append("\n## E6  Methods\n\n![](figures/e6_methods.png)\n\n" + piv.round(3).to_markdown() + "\n")

    bw = load(raw, "boreas_weather*.csv")
    if not bw.empty:
        order = ["sunny", "overcast", "snow_ground", "snowfall", "rain", "night"]
        g = agg(bw, ["stratum"]).set_index("stratum").reindex([o for o in order if o in set(bw.stratum)]).reset_index()
        fig, ax = plt.subplots(figsize=(6.4, 3.8))
        ax.bar(range(len(g)), g[METRIC], 0.6, color=PAL[0])
        ax.errorbar(range(len(g)), g[METRIC], yerr=[g[METRIC] - g[METRIC + "_lo"], g[METRIC + "_hi"] - g[METRIC]], fmt="none", ecolor=INK, lw=1, capsize=3)
        for i, s in enumerate(g.stratum):
            pts = bw[bw.stratum == s][METRIC]
            ax.scatter(np.full(len(pts), i) + np.random.default_rng(0).uniform(-0.15, 0.15, len(pts)), pts, s=10, color=INK2, zorder=3)
        ax.set_xticks(range(len(g)), g.stratum); ax.set_ylabel("pose AUC@10° vs GNSS/INS"); ax.set_ylim(0, 1.05)
        ax.set_title("E1  Real weather (Boreas, same 4 places)", loc="left")
        fig.savefig(figs / "e1_real_weather.png"); plt.close(fig)
        md.append("\n## E1  Real weather (Boreas)\n\n![](figures/e1_real_weather.png)\n\n" + table_md(g, ["stratum", "n", METRIC, "reg_frac"]))
        md.append("\nPer sequence:\n\n" + agg(bw, ["stratum", "seq"]).pipe(table_md, ["stratum", "seq", "n", METRIC, "reg_frac"]))

    bs = load(raw, "boreas_synth*.csv")
    if not bs.empty:
        g = agg(bs, ["perturb", "severity"]).sort_values(["perturb", "severity"])
        md.append("\n## E1-gap  Synthetic weather applied to the sunny Boreas runs\n\n" + table_md(g, ["perturb", "severity", "n", METRIC, "reg_frac"]))
        if not bw.empty:
            fig, ax = plt.subplots(figsize=(6.4, 4))
            real = agg(bw, ["stratum"]).set_index("stratum")
            for i, (p, real_s) in enumerate([("rain", "rain"), ("snow", "snowfall"), ("night", "night"), ("fog", None)]):
                gp = g[g.perturb == p]
                if gp.empty:
                    continue
                ax.plot(gp.severity, gp[METRIC], color=PAL[i], marker="o", ms=4, label=f"synthetic {p}")
                if real_s and real_s in real.index:
                    ax.axhline(real.loc[real_s, METRIC], color=PAL[i], ls=":", lw=1.5)
                    ax.text(5.1, real.loc[real_s, METRIC], f"real {real_s}", color=INK2, fontsize=8, va="center")
            ax.set_xlabel("synthetic severity"); ax.set_ylabel("pose AUC@10°"); ax.set_ylim(-0.02, 1.02); ax.set_xlim(0.8, 6)
            ax.set_title("Synthetic vs real weather (dotted = real stratum)", loc="left"); ax.legend(fontsize=8, loc="lower left")
            fig.savefig(figs / "e1_synth_vs_real.png"); plt.close(fig)
            md.append("\n![](figures/e1_synth_vs_real.png)\n")

    bx = load(raw, "boreas_xseason*.csv")
    if not bx.empty:
        g = agg(bx, ["stratum"], metrics=("query_reg", "cross_auc@10"))
        order = ["sunny", "overcast", "snow_ground", "snowfall", "rain", "night"]
        g = g.set_index("stratum").reindex([o for o in order if o in set(g.stratum)]).reset_index()
        fig, ax = plt.subplots(figsize=(6.4, 3.8))
        x = np.arange(len(g))
        ax.bar(x - 0.18, g["query_reg"], 0.34, color=PAL[0], label="query images registered")
        ax.bar(x + 0.18, g["cross_auc@10"], 0.34, color=PAL[1], label="map↔query pose AUC@10°")
        ax.set_xticks(x, g.stratum); ax.set_ylim(0, 1.05); ax.legend(fontsize=8)
        ax.set_title("E7  Localising other conditions in a sunny map", loc="left")
        fig.savefig(figs / "e7_xseason.png"); plt.close(fig)
        md.append("\n## E7  Cross-season localisation\n\n![](figures/e7_xseason.png)\n\n" + table_md(g, ["stratum", "n", "query_reg", "cross_auc@10"]))

    (out / "summary.md").write_text("\n".join(md))
    print("wrote", out / "summary.md")


if __name__ == "__main__":
    main()
